const CATEGORY_INDEX = new Map(
  Object.entries(CATEGORY_HINTS).map(([k, v]) => [k.replace(/\s+/g, ''), v]),
);

/** 是否是「类别写法」；是则返回标签解释，否则 null */
export function getCategoryHint(name) {
  const key = String(name || '').replace(/\s+/g, '');
  return CATEGORY_INDEX.get(CATEGORY_ALIASES[key] || key) || null;
}

